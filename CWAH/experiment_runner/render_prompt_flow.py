"""Render a reviewable snapshot of the current CWAH prompt flows."""

import importlib.util
from pathlib import Path


TRACE_ROOT = Path(__file__).resolve().parents[2]
GAME_ROOT = TRACE_ROOT / "CWAH" / "CWAH-MultiPlayer"
LLM_ROOT = GAME_ROOT / "LLM"
OUTPUT = TRACE_ROOT / "docs" / "CWAH_PROMPT_FLOW_REVIEW.txt"
BELIEF_JSON = "[RUNTIME_TRACE_BELIEF_JSON]"


def _composer():
    path = LLM_ROOT / "prompt_composer.py"
    spec = importlib.util.spec_from_file_location("cwah_review_prompt_composer", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _template(name):
    return (LLM_ROOT / name).read_text(encoding="utf-8")


def _section(title, sources, body):
    return ("\n" + "=" * 88 + "\n" + title + "\n"
            + "Sources: " + ", ".join(sources) + "\n" + "=" * 88 + "\n\n"
            + body.rstrip() + "\n")


def main():
    composer = _composer()
    active_alice = _template("prompt_Alice.txt")
    active_bob = _template("prompt_Bob.txt")
    active_peer = _template("prompt_Peer.txt")
    reply_alice = _template("prompt_Reply_Alice.txt")
    reply_bob = _template("prompt_Reply_Bob.txt")
    reply_fragment = (LLM_ROOT / "prompts" / "trace" / "reply_context.txt").read_text(
        encoding="utf-8").replace("$TRACE_BELIEF", BELIEF_JSON)

    header = """CWAH PROMPT FLOW — REVIEW SNAPSHOT

Generated by: python CWAH/experiment_runner/render_prompt_flow.py
Scope: current Runner defaults, plus the CLI's prompt_Peer.txt fallback.
This file contains the full static text after prompt_composer has selected and
joined the appropriate fragments. Bracketed RUNTIME markers stand for values
provided at a decision; ordinary $VARIABLES are also filled at runtime.
No API key, private experiment JSON, model output, or real belief is included.
Archived prompts, explicit custom template overrides, and retry feedback are
outside this snapshot. Qwen uses the same role-specific Reply prompts as APIs.

FLOW A — TRACE off
  1. Alice Active and Bob Active select actions from the same step-start snapshot.
  2. Deliver selected messages after both actions have been chosen.
  3. If Bob sent a message, Alice Reactive replies. If Alice sent a message,
     Bob Reactive replies. A reply does not trigger another immediate reply.

FLOW B — TRACE on
  1. TRACE Updater runs before Alice Active; Bob Active still uses the baseline
     prompt and is shown in Flow A below.
  2. Both Active actions are chosen, then messages are delivered.
  3. If Alice sent a message, Bob Reactive uses the same prompt as Flow A.
  4. If Bob sent a message, TRACE Updater runs again immediately before Alice
     Reactive; Alice then receives the updated belief in her Reply prompt.
  5. Updater is one template reused at both TRACE decision boundaries.

Runtime Active placeholders: $GOAL, $STEP, $PROGRESS, $PUBLIC_TASKS,
$AGENT_CONTROL, $ACTION_HISTORY, $DIALOGUE_HISTORY, $ACTIONS_REFINE,
and Bob's $ASSIGNED_PERSONALITY. [RUNTIME_TRACE_BELIEF_JSON] is the structured
Intent/Capability/Reliability/Uncertainty value for Alice when TRACE is on.
Runtime Reply placeholders additionally include $CURRENT_SKILL and
$INCOMING_MESSAGE. Updater replaces $INFORMATION, $PRIOR, $SUPPORT, $EVENTS,
and $REQUESTS with JSON before calling the model.
"""

    sections = [
        _section("A1. Alice Active — TRACE off",
                 ["LLM/prompt_Alice.txt", "LLM/prompts/baseline/active_output.txt"],
                 composer.compose_active(active_alice, "")),
        _section("A2. Bob Active — both TRACE modes",
                 ["LLM/prompt_Bob.txt", "LLM/prompts/baseline/active_output.txt"],
                 composer.compose_active(active_bob, "")),
        _section("A3. Alice Reactive Reply — TRACE off, when Bob messages",
                 ["LLM/prompt_Reply_Alice.txt"],
                 composer.compose_reply(reply_alice, "")),
        _section("A4. Bob Reactive Reply — both TRACE modes, when Alice messages",
                 ["LLM/prompt_Reply_Bob.txt"],
                 composer.compose_reply(reply_bob, "")),
        _section("B1/B4. TRACE Updater — before Alice Active or Reactive",
                 ["LLM/prompts/trace/updater.txt"],
                 (LLM_ROOT / "prompts" / "trace" / "updater.txt").read_text(
                     encoding="utf-8")),
        _section("B2. Alice Active — TRACE on",
                 ["LLM/prompt_Alice.txt", "LLM/prompts/trace/planner_context.txt",
                  "LLM/prompts/trace/communication.txt",
                  "LLM/prompts/trace/active_output.txt"],
                 composer.compose_active(active_alice, "TRACE_ENABLED").replace(
                     "$TRACE_BELIEF", BELIEF_JSON)),
        _section("B4. Alice Reactive Reply — TRACE on, when Bob messages",
                 ["LLM/prompt_Reply_Alice.txt", "LLM/prompts/trace/reply_context.txt"],
                 composer.compose_reply(reply_alice, reply_fragment).replace(
                     "$TRACE_BELIEF", reply_fragment)),
        _section("OPTIONAL CLI FALLBACK. Peer Active — TRACE off",
                 ["LLM/prompt_Peer.txt", "LLM/prompts/baseline/active_output.txt"],
                 composer.compose_active(active_peer, "")),
        _section("OPTIONAL CLI FALLBACK. Peer Active — TRACE on",
                 ["LLM/prompt_Peer.txt", "LLM/prompts/trace/planner_context.txt",
                  "LLM/prompts/trace/communication.txt",
                  "LLM/prompts/trace/active_output.txt"],
                 composer.compose_active(active_peer, "TRACE_ENABLED").replace(
                     "$TRACE_BELIEF", BELIEF_JSON)),
    ]
    OUTPUT.write_text(header + "".join(sections), encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
